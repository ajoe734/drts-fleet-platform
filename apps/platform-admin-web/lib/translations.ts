export function formatNoticeWindow(
  start: string | null,
  end: string | null,
  t: TranslateFn,
): string {
  if (!start && !end) {
    return t("notices.window.notScheduled");
  }
  if (start && end) {
    return `${start} - ${end}`;
  }
  return start ?? end ?? "";
}

