function findRepositoryRoot(startDir) {
  let current = path.resolve(startDir);

  while (true) {
    if (
      fs.existsSync(path.join(current, "pnpm-workspace.yaml")) &&
      fs.existsSync(path.join(current, "docs"))
    ) {
      return current;
    }

    const parent = path.dirname(current);
    if (parent === current) {
      throw new Error("Unable to locate repository root for assistant corpus.");
    }
    current = parent;
  }
}

function headingAllowed(entry, heading) {
  if (!entry.headingPrefixes || entry.headingPrefixes.length === 0) {
    return true;
  }

  return entry.headingPrefixes.some((prefix) => heading.startsWith(prefix));
}

function countMarkdownChunks(content, entry) {
  const lines = content.split(/\r?\n/);
  let chunkCount = 0;
  let currentHeading = null;
  let hasBody = false;

  const flush = () => {
    if (currentHeading && hasBody && headingAllowed(entry, currentHeading)) {
      chunkCount += 1;
    }
    hasBody = false;
  };

  for (const rawLine of lines) {
    const line = rawLine || "";
    const headingMatch = /^(#{1,6})\s+(.*)$/.exec(line);
    if (headingMatch) {
      flush();
      currentHeading = (headingMatch[2] || "").trim();
      continue;
    }

    if (line.trim()) {
      hasBody = true;
    }
  }

  flush();
  return chunkCount;
}

function countCanvasChunks(content) {
  return Array.from(content.matchAll(/<DCSection\b[\s\S]*?<\/DCSection>/g))
    .length;
}

