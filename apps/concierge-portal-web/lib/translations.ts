export const translations = { en, zh } as const;

export function t(key: string, locale: Locale, params: Params = {}) {
  const dict = translations[locale];
  const template =
    dict[key as keyof typeof dict] ?? en[key as keyof typeof en] ?? key;
  return Object.entries(params).reduce(
    (result, [paramKey, value]) =>
      result.replaceAll(`{${paramKey}}`, String(value)),
    template,
  );
}

export function getLocaleHtmlLang(locale: Locale) {
  return locale === "zh" ? "zh-TW" : "en";
}
